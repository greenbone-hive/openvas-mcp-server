#!/usr/bin/env python3
"""Render the MCP tool reference from a running gvm-mcp binary.

The reference is generated, never hand-written: the script starts the server
on stdio once per toolset, performs the MCP handshake, lists the tools and
writes one Markdown page per toolset plus an index under
``docs/reference/tools``. CI regenerates the pages and fails on drift.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "docs" / "reference" / "tools"
PROTOCOL_VERSION = "2025-06-18"
HEADER = "<!-- Generated by scripts/render_tool_reference.py; do not edit by hand. -->"


class ToolDumpError(RuntimeError):
    """The server did not answer the MCP handshake or tool listing."""


def mcp_tools(binary: Path, toolsets: str) -> list[dict[str, Any]]:
    """Return ``tools/list`` of ``binary`` started with ``--toolsets``."""
    command = [
        str(binary),
        "--toolsets",
        toolsets,
        # Listing tools never contacts the gateway; point at a closed port so a
        # stray request fails fast instead of reaching a real deployment.
        "--gateway-url",
        "http://127.0.0.1:9",
    ]
    with subprocess.Popen(
        command,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    ) as proc:
        assert proc.stdin is not None and proc.stdout is not None

        def send(message: dict[str, Any]) -> None:
            proc.stdin.write(json.dumps(message) + "\n")
            proc.stdin.flush()

        def receive() -> dict[str, Any]:
            line = proc.stdout.readline()
            if not line:
                detail = proc.stderr.read() if proc.stderr else ""
                raise ToolDumpError(f"server closed stdout: {detail.strip()[-500:]}")
            payload = json.loads(line)
            if "error" in payload:
                raise ToolDumpError(f"server error: {payload['error']}")
            return payload

        send(
            {
                "jsonrpc": "2.0",
                "id": 1,
                "method": "initialize",
                "params": {
                    "protocolVersion": PROTOCOL_VERSION,
                    "capabilities": {},
                    "clientInfo": {"name": "render_tool_reference", "version": "0"},
                },
            }
        )
        receive()
        send({"jsonrpc": "2.0", "method": "notifications/initialized"})

        tools: list[dict[str, Any]] = []
        cursor: str | None = None
        request_id = 2
        while True:
            params = {"cursor": cursor} if cursor else {}
            send({"jsonrpc": "2.0", "id": request_id, "method": "tools/list", "params": params})
            result = receive()["result"]
            tools.extend(result["tools"])
            cursor = result.get("nextCursor")
            request_id += 1
            if not cursor:
                break
        proc.stdin.close()
        proc.terminate()
    return tools


def list_toolsets(binary: Path) -> list[tuple[str, str]]:
    """Return ``(name, scope)`` pairs from ``--list-toolsets`` in server order."""
    output = subprocess.run(
        [str(binary), "--list-toolsets"], check=True, capture_output=True, text=True
    ).stdout
    toolsets = []
    for line in output.splitlines():
        match = re.match(r"^(\S+)\s+(.*\S)\s*$", line)
        if match:
            toolsets.append((match.group(1), match.group(2)))
    if not toolsets:
        raise ToolDumpError("--list-toolsets printed no toolsets")
    return toolsets


def escape_cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def type_label(schema: dict[str, Any], defs: dict[str, Any]) -> tuple[str, bool]:
    """Return a human type label and whether ``null`` is accepted."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return type_label(defs.get(name, {}), defs)
    raw = schema.get("type")
    types = raw if isinstance(raw, list) else ([raw] if raw else [])
    nullable = "null" in types
    types = [t for t in types if t != "null"]
    if not types:
        if "enum" in schema:
            types = ["string"]
        elif "anyOf" in schema or "oneOf" in schema:
            variants = schema.get("anyOf") or schema.get("oneOf")
            labels = []
            for variant in variants:
                label, variant_nullable = type_label(variant, defs)
                nullable = nullable or variant_nullable
                if label != "null":
                    labels.append(label)
            types = labels or ["any"]
        else:
            types = ["any"]
    labels = []
    for base in types:
        if base == "array":
            items = schema.get("items")
            item_label = type_label(items, defs)[0] if isinstance(items, dict) else "any"
            labels.append(f"array<{item_label}>")
        elif base == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                labels.append(f"object<string, {type_label(extra, defs)[0]}>")
            else:
                labels.append("object")
        elif base == "integer" and schema.get("format"):
            labels.append("integer")
        else:
            labels.append(str(base))
    label = " | ".join(dict.fromkeys(labels))
    if "enum" in schema:
        values = ", ".join(f"`{value}`" for value in schema["enum"] if value is not None)
        label = f"{label} ({values})"
    return label, nullable


def resolve(schema: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    if "$ref" in schema:
        return defs.get(schema["$ref"].rsplit("/", 1)[-1], {})
    return schema


def object_fields(prop: dict[str, Any], defs: dict[str, Any]) -> str:
    """Describe the fields of an object-typed parameter or array item."""
    schema = resolve(prop, defs)
    items = schema.get("items")
    target = resolve(items, defs) if isinstance(items, dict) else schema
    properties = target.get("properties")
    if not isinstance(properties, dict) or not properties:
        return ""
    required = set(target.get("required") or [])
    parts = []
    for name, field in properties.items():
        if not isinstance(field, dict):
            continue
        label, _ = type_label(field, defs)
        flag = "required" if name in required else "optional"
        text = " ".join((field.get("description") or "").split())
        parts.append(f"`{name}` ({label}, {flag}){': ' + text if text else ''}")
    return "; ".join(parts) + "."


def parameter_rows(tool: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    schema = tool.get("inputSchema", {})
    defs = schema.get("$defs") or schema.get("definitions") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, prop in (schema.get("properties") or {}).items():
        if not isinstance(prop, dict):
            continue
        label, _ = type_label(prop, defs)
        constraints = []
        if "minimum" in prop:
            constraints.append(f"min {prop['minimum']}")
        if "maximum" in prop:
            constraints.append(f"max {prop['maximum']}")
        if "default" in prop:
            constraints.append(f"default `{prop['default']}`")
        description = prop.get("description") or ""
        if constraints:
            description = f"{description} ({', '.join(constraints)})".strip()
        item_fields = object_fields(prop, defs)
        if item_fields:
            description = f"{description} Each item: {item_fields}".strip()
        rows.append(
            (
                f"`{name}`",
                escape_cell(label),
                "yes" if name in required else "no",
                escape_cell(description),
            )
        )
    return rows


def tool_section(tool: dict[str, Any]) -> str:
    annotations = tool.get("annotations") or {}
    badges = []
    if annotations.get("readOnlyHint"):
        badges.append("read-only")
    elif annotations.get("destructiveHint"):
        badges.append("destructive")
    else:
        badges.append("mutating")
    title = annotations.get("title") or tool["name"]
    lines = [f"### `{tool['name']}`", "", f"**{escape_cell(title)}** · {' · '.join(badges)}", ""]
    description = " ".join(tool.get("description", "").split())
    if description:
        lines += [description, ""]
    rows = parameter_rows(tool)
    if rows:
        lines += [
            "| Parameter | Type | Required | Description |",
            "| --- | --- | --- | --- |",
            *(f"| {name} | {label} | {req} | {desc} |" for name, label, req, desc in rows),
            "",
        ]
    else:
        lines += ["This tool takes no parameters.", ""]
    return "\n".join(lines)


def toolset_page(name: str, scope: str, tools: list[dict[str, Any]], default: bool) -> str:
    read_only = sum(1 for tool in tools if (tool.get("annotations") or {}).get("readOnlyHint"))
    lines = [
        HEADER,
        "",
        f"# {name}",
        "",
        scope + ".",
        "",
        f"- Toolset name: `{name}`",
        f"- Enabled by default: {'yes' if default else 'no (opt-in with `--toolsets default,' + name + '`)'}",
        f"- Tools: {len(tools)} ({read_only} read-only)",
        "",
        "## Tools",
        "",
        *(tool_section(tool) for tool in tools),
    ]
    return "\n".join(lines).rstrip() + "\n"


def index_page(entries: list[dict[str, Any]], total: int, total_read_only: int) -> str:
    lines = [
        HEADER,
        "",
        "# Tool reference",
        "",
        f"`gvm-mcp` exposes {total} tools in {len(entries)} toolsets; {total_read_only} of them",
        "are read-only. Tool and parameter names follow gvmd's own vocabulary, so",
        "what you know from the web interface applies here. Choose toolsets with",
        "`--toolsets` and drop every mutating tool with `--read-only` (see",
        "[Toolsets](../../toolsets.md)).",
        "",
        "| Toolset | Scope | Tools | Read-only | Default |",
        "| --- | --- | ---: | ---: | --- |",
    ]
    for entry in entries:
        lines.append(
            f"| [{entry['name']}]({entry['name']}.md) | {escape_cell(entry['scope'])} | "
            f"{entry['count']} | {entry['read_only']} | {'yes' if entry['default'] else 'opt-in'} |"
        )
    lines += [
        "",
        "```{toctree}",
        ":hidden:",
        ":maxdepth: 1",
        "",
        *(entry["name"] for entry in entries),
        "```",
    ]
    return "\n".join(lines) + "\n"


def render(binary: Path, output: Path) -> dict[str, str]:
    toolsets = list_toolsets(binary)
    default_names = {tool["name"] for tool in mcp_tools(binary, "default")}
    # `system` is always enabled, so subtract it from every other toolset.
    system_names = {tool["name"] for tool in mcp_tools(binary, "system")}
    pages: dict[str, str] = {}
    entries = []
    seen: set[str] = set()
    for name, scope in toolsets:
        tools = mcp_tools(binary, name)
        if name != "system":
            tools = [tool for tool in tools if tool["name"] not in system_names]
        tools = [tool for tool in tools if tool["name"] not in seen]
        seen.update(tool["name"] for tool in tools)
        default = all(tool["name"] in default_names for tool in tools)
        read_only = sum(1 for tool in tools if (tool.get("annotations") or {}).get("readOnlyHint"))
        entries.append(
            {"name": name, "scope": scope, "count": len(tools), "read_only": read_only, "default": default}
        )
        pages[f"{name}.md"] = toolset_page(name, scope, tools, default)
    total = sum(entry["count"] for entry in entries)
    total_read_only = sum(entry["read_only"] for entry in entries)
    pages["index.md"] = index_page(entries, total, total_read_only)
    return pages


def write_pages(pages: dict[str, str], output: Path) -> list[Path]:
    output.mkdir(parents=True, exist_ok=True)
    stale = [path for path in output.glob("*.md") if path.name not in pages]
    for path in stale:
        path.unlink()
    changed = []
    for name, content in pages.items():
        path = output / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(path)
    return changed + stale


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=ROOT / "target" / "release" / "gvm-mcp")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the rendered pages differ from the files on disk",
    )
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    try:
        pages = render(args.binary.resolve(), args.output)
    except (OSError, subprocess.CalledProcessError, ToolDumpError, KeyError, json.JSONDecodeError) as error:
        print(f"tool reference rendering failed: {error}", file=sys.stderr)
        return 1
    if args.check:
        drift = [
            name
            for name, content in pages.items()
            if not (args.output / name).exists()
            or (args.output / name).read_text(encoding="utf-8") != content
        ]
        drift += [path.name for path in args.output.glob("*.md") if path.name not in pages]
        if drift:
            print("tool reference is out of date: " + ", ".join(sorted(drift)), file=sys.stderr)
            print("run: python3 scripts/render_tool_reference.py", file=sys.stderr)
            return 1
        print(f"tool reference is current ({len(pages) - 1} toolsets)")
        return 0
    changed = write_pages(pages, args.output)
    print(f"rendered {len(pages)} pages into {args.output} ({len(changed)} changed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
